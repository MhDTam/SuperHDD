#pragma once
#define SHDD_PROTOCOL_VERSION 2
#define SHDD_BLOCK_BYTES 65536u
/* FILE_APPEND_DATA is incompatible with noncached backing-file creation. */
#define SHDD_BACKING_ACCESS (FILE_READ_DATA|FILE_WRITE_DATA|FILE_READ_ATTRIBUTES|FILE_WRITE_ATTRIBUTES|SYNCHRONIZE|DELETE)
#define SHDD_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_DATA)
#define SHDD_IOCTL_ATTACH CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define SHDD_IOCTL_DETACH CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define SHDD_IOCTL_PAUSE CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
#define SHDD_IOCTL_CLEAR CTL_CODE(FILE_DEVICE_UNKNOWN,0x804,METHOD_BUFFERED,FILE_READ_DATA|FILE_WRITE_DATA)
typedef struct _SHDD_ATTACH {
    ULONG Version;
    ULONG DisposableVolumeAcknowledged;
    ULONGLONG CapacityBytes;
    WCHAR SourceDevice[260];
    WCHAR BackingFile[520];
} SHDD_ATTACH;
typedef struct _SHDD_STATUS {
    ULONG Version;
    ULONG Attached;
    ULONG Paused;
    ULONG ExperimentalAttachEnabled;
    ULONGLONG Hits, Misses, SourceReadBytes, SsdReadBytes, FillBytes, Evictions, Errors, Generation;
    ULONGLONG CapacityBytes, SourceLength;
    ULONG ActiveMutations, PendingReads, CacheDisabled, Reserved;
    ULONGLONG ReadBypasses;
    ULONG QueueLimit, MaxReadBytes;
} SHDD_STATUS;
